S_4137 = '''#### 4.13.7 照片矩形必须过 CTM：牛皮纸「贴纸只能往左上拖」的根因（第十五轮）

用户报：「有个bug这个牛皮纸，插入的贴纸无法往右以及往下拖拽」。

根因不在贴纸代码里，而在 §4.13.6 引入的那个中间量上新长出来的一个漏洞：
**`paintPhoto` 返回的矩形是「调用点的局部坐标」，却被当成「画布像素」用。**

牛皮纸模版是**先 translate + rotate 再画照片**的：

```js
ctx.translate(W/2, H*.45); ctx.rotate(-.028);
c.plate(-pw/2, -ph/2, pw, ph, 0, 'rgba(0,0,0,.36)', W*.02, 0);
c.paint(-pw/2, -ph/2, pw, ph, 0);
```

`drawFit()` 在 `c.paint` 内部量出来的矩形因此是 `dx=-345.6, dy=-460.8`（960×1280 画布）——
矩形有 **3/4 落在画布外**，中心正好压在**画布左上角**。修前 / 修后实测：

| 牛皮纸 · 960×1280 | 修前 | 修后 |
| --- | --- | --- |
| `photoRect` | `-345.6,-460.8,691.2,921.6` | `123.8,182.5,712.4,787.1`（中心 `480/576` = 它的版心） |
| 贴纸 `(.5,.5)` 画在画布 | `x = -1.1`（**贴到画布左边缘外面**） | `765, 891.5`（照片中心） |
| 往右拖（瞄 `0.85`） | **得到 `0.50`（纹丝不动）** | 得到 `0.849` |
| 往下拖（瞄 `0.85`） | **得到 `0.30`（还是上一次的值）** | 得到 `0.849` |
| 往左拖 / 往上拖 | 能动 | 能动 |

"往右/往下纹丝不动"的机制：面板换算 `s.x = clamp((px - rc.dx)/dw, 0, 1)`。
`rc.dx = -345.6` 时，光标只要不在画布最左侧那一条窄带里，`px - rc.dx` 就是正的很大值、
除以 `dw` 之后超过 1 → 被夹成 **1**；而 `s.y` 同理。于是"往右/往下"这两个方向
**永远只能落在同一个被夹住的值上**，看起来就是拖不动；"往左/往上"恰好落回带内，能动 ——
症状因此精确地表现为**只能往左上拖**。

**改法：`rectThruM(rc, ctx.getTransform())`** —— 把矩形四个角过一遍**绘制那一刻的 CTM**、
取外接矩形。三条纪律：

1. **没有变换就原样返回**，不要绕一圈。绕一圈会带进浮点噪声：`x1-x0` 与 `rc.dw`
   在数值上等价、却不保证按位相同，而 `renderCanvas` 挑"面积最大的那次 paint"用的是
   严格 `>` —— 噪声足以打破平局（见下面九宫格）。
2. **不返回矩阵。** 返回矩阵等于给"两套坐标系"开后门（硬约定 45）。
   取外接矩形的代价：四个角最多差 `半宽 × sin(角度)`（牛皮纸 1.6° → 约 1.6%）；
   而**旋转下矩形的中心点不变**，所以 `(.5,.5)` 仍然精确 —— 那正是最要紧的一格。
3. **再与画框求交。** `paint(x,y,w,h)` 是 cover（铺满这个框、多出来的裁掉），
   所以"照片看得见的部分"= 铺出来的矩形 ∩ 画框。不求交的话，溢出的那一圈也被算成照片：
   明信片上下各 **158px**、电影感 173px、霓虹 136px、极简 64px、宝丽来 3px ——
   贴纸在这些边上会飘到照片外面，而面板画的虚线还写在"照片边界"上，自相矛盾。
   （`contain` 时矩形本来就小于画框，求交是恒等变换，不会误伤。）

**顺带查出两个同源缺陷**（这两个"只看牛皮纸"是发现不了的）：

| 模版 | 缺陷 | 修前 → 修后 |
| --- | --- | --- |
| `duotone` 双色 | **压根不调 `c.paint`**：它自己 `makeDuotone()` 重着色之后 `ctx.drawImage`。没人吭声 → `photoRect` 退化成"整块画布"，贴纸锚在画布中心而不是照片中心（**偏 90px**） | `0,0,960,1280` → `96,128,768,844.8` |
| `grid9` 九宫格 | 9 格里"面积最大者胜"用严格 `>`，而九格面积**差在 1e-6 px² 以下** → 赢家由**舍入**决定，不由设计决定 | 去掉 1e-6 容差，它就从 `352.6,184` 跳到 `623.7,455`（实测） |

双色的补法是给 `cx` 加一个 `declare(x,y,w,h)`：语法糖而已，语义是"照片就占这个框"，
不再跑一次 fit 计算 —— 让"我自己贴上去的照片"也能进入同一个坐标系。

> **⚠ 关于九宫格的一个容易记错的机制**：它**不是**"跑一次一个样"。
> 同一份代码里连渲 12 次是**同值**的（实测），只是那个值由 <1e-6 的舍入差裁决。
> 所以"连渲 N 次对比"这条检测器**抓不到它**；抓它的是
> "把容差拿掉、看赢家会不会换格子"（`.workbuddy/tmp/_iso_rect.mjs`）。

**为什么必须对全部 11 个模版量一遍**：牛皮纸只是最显眼的一个。修前"矩形越出画布"的有
`kraft / polaroid / postcard` 三个，加上"溢出撑大"的 `neon / minimal / cinematic`
和上面两个退化 —— 一共 **8 个**模版有毛病。只看用户点名的那个，会漏掉 7 个。
'''

